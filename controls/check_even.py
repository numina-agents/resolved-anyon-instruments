"""Two small controls for the arbitrary-abelian argument."""
import itertools
import numpy as np

# A=F_2^3, omega=(-1)^(a1 b2 c3), a=(1,1,1): self-dual quaternionic cup.
A=list(itertools.product(range(2),repeat=3))
X=np.array([[0,1],[1,0]],complex)
Z=np.diag([1,-1]).astype(complex)
I=np.eye(2)
a=(1,1,1)
def t(a,b,c):return a[0]*b[1]*c[2]%2
def beta(a,x,y):return (t(a,x,y)+t(x,y,a)-t(x,a,y))%2
def gamma(x,a,b):return (t(a,b,x)+t(x,a,b)-t(a,x,b))%2
def add(x,y):return tuple((u+v)%2 for u,v in zip(x,y))
def rep(x):
    q=(1j)**x[1]*(-1)**(x[0]*x[1]+x[0]*x[2]+x[1]*x[2])
    return q*np.linalg.matrix_power(X,(x[0]+x[1])%2)@np.linalg.matrix_power(Z,(x[1]+x[2])%2)
for x,y in itertools.product(A,repeat=2):
    assert np.allclose(rep(x)@rep(y),(-1)**beta(a,x,y)*rep(add(x,y)))
U=X@Z
for x in A:
    desired=(-1)**gamma(x,a,a)*rep(x).conj()
    assert np.allclose(U@rep(x)@U.conj().T,desired)
bell=np.eye(2).reshape(-1)/np.sqrt(2)
cup=np.kron(I,U.conj().T)@bell
for x in A:
    assert np.allclose((-1)**gamma(x,a,a)*np.kron(rep(x),rep(x))@cup,cup)
assert np.allclose(U.T,-U)
print('PASS F2^3: multiplier and self-dual antisymmetric Clifford cup')

# A=C4^3, omega=i^(a1 b2 c3), two flux e1 charges: output flux 2e1.
d=4
shift=np.roll(np.eye(d),1,axis=0)
clock=np.diag((1j)**np.arange(d))
rho={}
for x in itertools.product(range(4),repeat=3):
    local=np.linalg.matrix_power(shift,x[2])@np.linalg.matrix_power(clock,x[1])
    rho[x]=np.kron(local,local)
# R_(2e1) generated by e1,2e2,2e3; e1 acts trivially. Four nonzero isotypes.
Pz=rho[(0,2,0)]
Px=rho[(0,0,2)]
assert np.allclose(Pz@Px,Px@Pz)
projectors=[]
for ez,ex in itertools.product([1,-1],repeat=2):
    proj=(np.eye(16)+ez*Pz)@(np.eye(16)+ex*Px)/4
    assert np.allclose(proj@proj,proj)
    assert round(np.trace(proj).real)==4
    projectors.append(proj)
assert np.allclose(sum(projectors),np.eye(16))
print('PASS C4^3: four coarse charge projectors, each rank4 = irreducible2 x multiplicity2')

# The stronger, excluded binary middle-pair vacuum instrument on two qutrit cups.
p=3
bell=np.eye(p).reshape(-1)/np.sqrt(p)
psi=np.kron(bell,bell).reshape((p,)*4)
vac=np.zeros_like(psi)
for i,k in itertools.product(range(p),repeat=2):vac[i,k,k,i]=1/p**2
failed=psi-vac
assert np.count_nonzero(np.abs(failed)>1e-9)==2*p*p-p
assert np.isclose(np.vdot(failed,failed).real,1-1/p**2)
print('PASS excluded binary resource: failure probability8/9, support15 (not a qutrit stabilizer state)')
